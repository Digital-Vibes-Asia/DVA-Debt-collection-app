const CURRENCIES = {
  SGD: { sym: 'S$',  locale: 'en-SG', decimals: 2, flag: '🇸🇬' },
  MYR: { sym: 'RM',  locale: 'ms-MY', decimals: 2, flag: '🇲🇾' },
  IDR: { sym: 'Rp',  locale: 'id-ID', decimals: 0, flag: '🇮🇩' },
  PHP: { sym: '₱',   locale: 'en-PH', decimals: 2, flag: '🇵🇭' },
  THB: { sym: '฿',   locale: 'th-TH', decimals: 2, flag: '🇹🇭' },
  VND: { sym: '₫',   locale: 'vi-VN', decimals: 0, flag: '🇻🇳' },
};

function fmtMoney(amount, ccy = 'MYR') {
  const c = CURRENCIES[ccy] || CURRENCIES.MYR;
  const n = new Intl.NumberFormat('en-US', {
    minimumFractionDigits: c.decimals,
    maximumFractionDigits: c.decimals,
  }).format(amount);
  return `${c.sym}${n}`;
}

// Buckets for aging
function bucketOf(daysOverdue) {
  if (daysOverdue <= 0)  return { key: 'current', label: 'Current',  color: '#15803D', bg: '#ECFDF3' };
  if (daysOverdue <= 30) return { key: '1-30',    label: '1–30 days', color: '#92400E', bg: '#FEF3C7' };
  if (daysOverdue <= 60) return { key: '31-60',   label: '31–60 days', color: '#B45309', bg: '#FFEDD5' };
  if (daysOverdue <= 90) return { key: '61-90',   label: '61–90 days', color: '#C2410C', bg: '#FFE4E6' };
  return                       { key: '90+',     label: '90+ days',   color: '#9F1239', bg: '#FFE4E6' };
}

// Initials from a full name
function initials(name) {
  return name.split(/\s+/).filter(Boolean).slice(0, 2).map(s => s[0]).join('').toUpperCase();
}

// Avatar color from name
const AVATAR_COLORS = [
  ['#FFE4E6', '#9F1239'],
  ['#E0F2FE', '#075985'],
  ['#DCFCE7', '#166534'],
  ['#FEF3C7', '#92400E'],
  ['#EDE9FE', '#5B21B6'],
  ['#FCE7F3', '#9D174D'],
  ['#CFFAFE', '#155E75'],
  ['#FED7AA', '#9A3412'],
];
function avatarColor(name) {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  return AVATAR_COLORS[h % AVATAR_COLORS.length];
}

